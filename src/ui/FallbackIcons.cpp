bool fallbackIcon(std::string_view name, Bitmap& out)
{
    for (const Drawing& drawing : Drawings) {
        if (drawing.name != name || drawing.rows.empty()) {
            continue;
        }
        size_t width = drawing.rows.front().size();
        Bitmap bitmap;
        bitmap.width = static_cast<uint32_t>(width);
        bitmap.height = static_cast<uint32_t>(drawing.rows.size());
        bitmap.rgba.reserve(width * drawing.rows.size() * 4);
        for (std::string_view row : drawing.rows) {
            if (row.size() != width) {
                return false;
            }
            for (char texel : row) {
                std::array<uint8_t, 4> color = paint(texel);
                bitmap.rgba.insert(bitmap.rgba.end(), color.begin(), color.end());
            }
        }
        out = std::move(bitmap);
        return true;
    }
    return false;
}

